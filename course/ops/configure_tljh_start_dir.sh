#!/usr/bin/env bash
set -euo pipefail

NOTEBOOK_DIR="~/student_workspace/notebooks"
CONFIG_PATH="/opt/tljh/config/jupyterhub_config.d/20-student-workspace.py"
RELOAD_HUB=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --notebook-dir)
      NOTEBOOK_DIR="$2"
      shift 2
      ;;
    --config-path)
      CONFIG_PATH="$2"
      shift 2
      ;;
    --no-reload)
      RELOAD_HUB=0
      shift
      ;;
    -h|--help)
      cat <<'EOF'
Usage:
  sudo bash course/ops/configure_tljh_start_dir.sh \
    [--notebook-dir ~/student_workspace/notebooks] \
    [--config-path /opt/tljh/config/jupyterhub_config.d/20-student-workspace.py]
EOF
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

mkdir -p "$(dirname "$CONFIG_PATH")"
cat > "$CONFIG_PATH" <<EOF
# Auto-generated by configure_tljh_start_dir.sh
c.Spawner.notebook_dir = "$NOTEBOOK_DIR"
EOF
chmod 644 "$CONFIG_PATH"

if [[ "$RELOAD_HUB" -eq 1 ]]; then
  tljh-config reload hub
fi

echo "configured TLJH notebook_dir: $NOTEBOOK_DIR"
